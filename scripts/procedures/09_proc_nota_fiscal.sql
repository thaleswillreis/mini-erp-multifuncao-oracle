DOCTO IN NUMBER,    (NÚMERO DO PEDIDO QUE SERÁ GERADO A NFE)
CFOP VARCHAR2,      (CÓDIGO FISCAL DE OPERAÇÕES E PRESTAÇÕES... 4 DÍGITOS)
