CREATE OR REPLACE FUNCTION md5 (
    valor VARCHAR2
) RETURN VARCHAR2 IS
    v_input        VARCHAR2(2000) := valor;
    v_input_cripto VARCHAR2(32) := NULL;
BEGIN
    -- Se o valor de entrada for nulo, retorna nulo direto para evitar erros
    IF v_input IS NULL THEN
        RETURN NULL;
    END IF;

    -- O número 2 representa o algoritmo MD5 dentro da DBMS_CRYPTO
    v_input_cripto := lower(rawtohex(dbms_crypto.hash(
        src => utl_raw.cast_to_raw(v_input),
        typ => 2
    )));

    RETURN v_input_cripto;
END;

   
